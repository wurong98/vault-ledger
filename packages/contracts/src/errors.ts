/**
 * 统一错误码。服务端与前端共用。
 * 语义：不可携带秘密信息，不回显原始敏感输入。
 */
export const ERROR_CODES = [
  'LOCKED',
  'SETUP_REQUIRED',
  'LLM_CONFIG_REQUIRED',
  'SETUP_ALREADY_DONE',
  'INVALID_PASSWORD_OR_BACKUP',
  'MODEL_UNAVAILABLE',
  'MODEL_RESPONSE_INVALID',
  'VALIDATION_FAILED',
  'REVISION_CONFLICT',
  'IDEMPOTENCY_CONFLICT',
  'UNSUPPORTED_BACKUP_VERSION',
  'BACKUP_INTEGRITY_FAILED',
  'BACKUP_TOO_LARGE',
  'LIMIT_EXCEEDED',
  'RATE_LIMITED',
  'STORAGE_LOCKED',
  'NOT_FOUND',
  'FORBIDDEN',
  'EXTRACTION_TIMEOUT',
  'INTERNAL_ERROR',
] as const;

export type ErrorCode = (typeof ERROR_CODES)[number];

export interface ApiErrorBody {
  code: ErrorCode;
  message: string;
  requestId?: string;
  /** 仅安全的字段级提示，例如 { amount: '金额最多两位小数' } */
  fields?: Record<string, string>;
}

const DEFAULT_STATUS: Record<ErrorCode, number> = {
  LOCKED: 401,
  SETUP_REQUIRED: 428,
  LLM_CONFIG_REQUIRED: 428,
  SETUP_ALREADY_DONE: 409,
  INVALID_PASSWORD_OR_BACKUP: 401,
  MODEL_UNAVAILABLE: 502,
  MODEL_RESPONSE_INVALID: 502,
  VALIDATION_FAILED: 400,
  REVISION_CONFLICT: 409,
  IDEMPOTENCY_CONFLICT: 409,
  UNSUPPORTED_BACKUP_VERSION: 422,
  BACKUP_INTEGRITY_FAILED: 422,
  BACKUP_TOO_LARGE: 413,
  LIMIT_EXCEEDED: 413,
  RATE_LIMITED: 429,
  STORAGE_LOCKED: 423,
  NOT_FOUND: 404,
  FORBIDDEN: 403,
  EXTRACTION_TIMEOUT: 504,
  INTERNAL_ERROR: 500,
};

export function statusForError(code: ErrorCode): number {
  return DEFAULT_STATUS[code] ?? 500;
}
